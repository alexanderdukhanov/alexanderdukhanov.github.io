function setLanguage(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (content[lang][key]) el.textContent = content[lang][key];
  });
  document.getElementById("about-text").textContent = longText[lang].about;
  document.getElementById("statement-text").textContent = longText[lang].statement;
  document.querySelectorAll(".lang").forEach(btn => btn.classList.toggle("active", btn.dataset.lang === lang));
  localStorage.setItem("portfolio-lang", lang);
}

document.querySelectorAll(".lang").forEach(btn => {
  btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
});

setLanguage(localStorage.getItem("portfolio-lang") || "en");
